//! Release packaging + publishing pipeline (Phase 3B operator tooling).
//!
//! This crate chains the frozen release surface end to end:
//!
//! 1. **Assemble** the canonical nine-entry flat release ZIP
//!    (`assemble.rs`) and immediately self-validate it through the single
//!    shared package validator (`desktop_todo_maintenance::package_zip`) —
//!    never a second copy of the ZIP security rules.
//! 2. **Facts** (`facts.rs`): SHA-256 + byte size of the *final* package
//!    bytes and of the two managed executables as they sit *inside the
//!    validated archive* — never guessed from pre-package sources.
//! 3. **Manifest** (`manifest.rs`): a deterministic, byte-stable
//!    schema-1 manifest generator over those facts. The generated bytes are
//!    validated with `update_core::validate_untrusted_manifest` and are then
//!    the exact bytes that get signed and served.
//! 4. **Sign** (`signing.rs`): delegation to the existing offline
//!    `desktop-todo-release-signer` — the production path runs the compiled
//!    production trust gate (which fails closed while the store is empty);
//!    the rehearsal path uses an explicitly injected TEST trust store. This
//!    crate implements no cryptography of its own.
//! 5. **Publish / read-back / mirror** (`publish.rs`): provider upload with
//!    an explicit collision/idempotence policy, byte-exact read-back
//!    verification, and cross-provider mirror consistency.
//!
//! Deliberate boundaries: this is operator tooling, not a runtime component
//! and never linked into a shipped binary. Publishing tools only ever touch
//! the public artifacts (ZIP, manifest, envelope) — the private signing seed
//! exists only inside the signer's operation lifetime and never enters this
//! crate, the network layer, or any log.

pub mod assemble;
pub mod facts;
pub mod manifest;
pub mod pipeline;
pub mod publish;
pub mod report;
pub mod signing;
